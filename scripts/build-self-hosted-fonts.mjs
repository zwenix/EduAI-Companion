#!/usr/bin/env node
/**
 * EduAI Companion — self-hosted web fonts.
 *
 * WHY THIS EXISTS
 * ---------------
 * The app loaded its typefaces from `https://fonts.googleapis.com/css2?...`.
 * On the school networks this product is built for that host is regularly
 * unreachable or blocked, and the browser logged
 *
 *   css2:1  Failed to load resource: net::ERR_CONNECTION_CLOSED
 *
 * on every single page load, leaving the whole UI on the fallback stack.
 *
 * This script copies the latin subsets of the @fontsource packages into
 * `public/fonts/` and writes one `public/fonts/fonts.css` with the matching
 * `@font-face` rules. Everything then loads from the app's own origin:
 *
 *   • the app shell      → `src/index.css` imports `/fonts/fonts.css`
 *   • document preview   → the srcdoc iframe links `/fonts/fonts.css`
 *   • print / PDF output → `src/lib/printUtils.ts` imports `/fonts/fonts.css`
 *
 * The generated folder is a build artifact (see .gitignore) — run
 * `npm run build:fonts` (or any `npm run build` / `npm run dev`, which call
 * it automatically) to refresh it.
 *
 * Usage:
 *   node scripts/build-self-hosted-fonts.mjs
 */

import { existsSync, mkdirSync, copyFileSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const OUT_DIR = join(ROOT, 'public', 'fonts');

/**
 * The families the product actually uses, with the weights it asks for.
 * The weights are the union of every `fonts.googleapis.com/css2` request the
 * app, the preview iframe, the print pipeline and the exported templates
 * used to make.
 */
const FAMILIES = [
  { pkg: 'fredoka', weights: [400, 500, 600, 700] },
  { pkg: 'inter', weights: [300, 400, 500, 600, 700, 800, 900] },
  { pkg: 'nunito', weights: [400, 500, 600, 700, 800, 900] },
  { pkg: 'comic-neue', weights: [300, 400, 700] },
  { pkg: 'patrick-hand', weights: [400] },
  { pkg: 'quicksand', weights: [400, 500, 600] },
  { pkg: 'kalam', weights: [300, 400, 700] },
  { pkg: 'lexend', weights: [300, 400, 500, 600, 700] },
  { pkg: 'space-grotesk', weights: [500, 700] },
  { pkg: 'jetbrains-mono', weights: [400] },
];

/** Character subsets to ship. `latin-ext` covers the accented characters. */
const SUBSETS = ['latin', 'latin-ext'];

const HEADER = `/* EduAI Companion — self-hosted web fonts.
 *
 * GENERATED by scripts/build-self-hosted-fonts.mjs — do not edit by hand.
 * Run \`npm run build:fonts\` to refresh.
 *
 * These fonts are served from the app's own origin so the UI keeps its
 * typography on school networks where fonts.googleapis.com is blocked.
 */`;

const collectFaces = () => {
  const faces = [];
  const copied = new Set();

  for (const { pkg, weights } of FAMILIES) {
    const pkgDir = join(ROOT, 'node_modules', '@fontsource', pkg);
    if (!existsSync(pkgDir)) {
      console.warn(`[fonts] @fontsource/${pkg} is not installed — skipping that family.`);
      continue;
    }

    for (const weight of weights) {
      for (const subset of SUBSETS) {
        const cssPath = join(pkgDir, `${subset}-${weight}.css`);
        if (!existsSync(cssPath)) continue; // subset not shipped for this weight

        const css = readFileSync(cssPath, 'utf8');
        const urls = [...css.matchAll(/url\(\.\/files\/([^)]+)\)/g)].map((m) => m[1]);
        if (urls.length === 0) continue;

        // Only the woff2 build is shipped — every browser the app supports
        // reads woff2, and the legacy .woff copy would double the payload.
        const woff2Files = urls.filter((file) => file.endsWith('.woff2'));
        if (woff2Files.length === 0) continue;

        for (const file of woff2Files) {
          const src = join(pkgDir, 'files', file);
          if (!existsSync(src)) continue;
          const dest = join(OUT_DIR, file);
          if (!copied.has(file)) {
            copyFileSync(src, dest);
            copied.add(file);
          }
        }

        faces.push(
          css
            // Point at the app origin instead of the package-relative path.
            .replace(/url\(\.\/files\//g, 'url(/fonts/')
            // Drop the legacy .woff source.
            .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '')
            .replace(/^\/\*[^*]*\*\/\s*$/gm, '')
            .trim(),
        );
      }
    }
  }

  return { faces, copied };
};

const main = () => {
  rmSync(OUT_DIR, { recursive: true, force: true });
  mkdirSync(OUT_DIR, { recursive: true });

  const { faces, copied } = collectFaces();
  if (faces.length === 0) {
    console.error('[fonts] No @font-face rules were produced — check that the @fontsource packages are installed.');
    process.exitCode = 1;
    return;
  }

  writeFileSync(join(OUT_DIR, 'fonts.css'), `${HEADER}\n\n${faces.join('\n\n')}\n`, 'utf8');

  const totalBytes = [...copied].reduce((sum, file) => {
    try {
      return sum + readFileSync(join(OUT_DIR, file)).length;
    } catch {
      return sum;
    }
  }, 0);

  console.log(
    `[fonts] Wrote ${faces.length} @font-face rules and ${copied.size} font files ` +
      `(${Math.round(totalBytes / 1024)} KB) to public/fonts/`,
  );
};

main();
