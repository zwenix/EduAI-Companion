/**
 * Route proxy calls to the secure full-stack backend
 */
export const generateEducationalContent = async (type: string, details: string) => {
  // Native app: no backend — call Gemini directly.
  if (isNativeApp()) {
    const result = await callGeminiClientDirect("generate-educational", { type, details });
    return result.text || "";
  }

  try {
    const response = await axios.post("/api/gemini/action", {
      action: "generate-educational",
      input: { type, details }
    }, {
      // Serverless backends (e.g. Vercel) hard-kill long generations; without a
      // client-side timeout the request can hang forever and the UI appears to
      // "time out". Abort after 60s so we seamlessly fall back to the
      // on-device Gemini engine below instead of leaving the user stuck.
      timeout: 60000
    });
    
    let resultText = response.data.text || "";
    // Clean up any top-level markdown wrappers if the AI wrapped the entire response in a code block
    resultText = resultText.trim();
    if (resultText.startsWith('```')) {
      const lines = resultText.split('\n');
      if (lines.length > 1 && lines[0].startsWith('```')) {
        lines.shift();
      }
      if (lines.length > 0 && lines[lines.length - 1].startsWith('```')) {
        lines.pop();
      }
      resultText = lines.join('\n').trim();
    }
    
    return resultText;
  } catch (error: any) {
    if (isBackendUnavailable(error)) {
      console.warn("[AI Routing] Backend unavailable — using client-side Gemini engine.");
      try {
        const result = await callGeminiClientDirect("generate-educational", { type, details });
        return result.text || "";
      } catch (clientErr: any) {
        checkAndReportApiError(clientErr, "Gemini");
        throw clientErr;
      }
    }
    console.error("Express /api/gemini/action failed:", error.message || error);
    checkAndReportApiError(error, "Gemini");
    throw error;
  }
};

function isContentTruncated(content: string): boolean {
  if (!content) return false;
  const trimmed = content.trim();
  if (trimmed.length < 300) return false;
  const lastPart = trimmed.slice(-60);
  const endsProperly = /[.!?)}>\]"]\s*$/.test(lastPart) || /<\/(div|section|article|table|p|ul|ol|li|h[1-6])>\s*$/i.test(lastPart);
  return !endsProperly;
}

const _fetchActionSingleBackend = async (action: string, input: any, onProgress?: (partial: any) => void) => {
  if (onProgress) {
    const response = await fetch("/api/gemini/action", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        action,
        input,
        stream: true
      })
    });
    
    if (!response.ok) {
      throw new Error(`HTTP error! status: ${response.status}`);
    }
    
    const reader = response.body?.getReader();
    const decoder = new TextDecoder("utf-8");
    let fullText = "";
    let leftover = "";
    let lastUpdateTime = 0;
    
    if (reader) {
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        
        const chunk = leftover + decoder.decode(value, { stream: true });
        const lines = chunk.split("\n");
        leftover = lines.pop() || "";
        
        for (const line of lines) {
          const trimmedLine = line.trim();
          if (trimmedLine.startsWith("data: ")) {
            const dataStr = trimmedLine.substring(6);
            try {
              const data = JSON.parse(dataStr);
              if (data.error) throw new Error(data.error);
              if (data.chunk) {
                fullText += data.chunk;
                const now = Date.now();
                if (now - lastUpdateTime > 150) {
                  const parsed = safeJsonParse(fullText);
                  if (parsed && Object.keys(parsed).length > 0) {
                    onProgress(parsed);
                    lastUpdateTime = now;
                  }
                }
              }
              if (data.final) {
                fullText = data.final;
              }
            } catch (e: any) {
              if (e.message && e.message !== "Unexpected end of JSON input" && !e.message.includes("Unexpected token")) {
                throw e;
              }
            }
          }
        }
      }
    }
    const parsed = safeJsonParse(fullText);
    if (parsed && Object.keys(parsed).length > 0) {
      onProgress(parsed);
    }
    if (!parsed || Object.keys(parsed).length === 0) {
      return { content: fullText || "Error: No content generated.", imagePrompt: "Classroom scene" };
    }
    return parsed;
  } else {
    const response = await axios.post("/api/gemini/action", {
      action,
      input
    });
    const parsed = response.data;
    if (!parsed || Object.keys(parsed).length === 0) {
      return { content: "Error: No content generated.", imagePrompt: "Classroom scene" };
    }
    return parsed;
  }
};

// Wrapper that transparently falls back to the client-side Gemini engine when
// the Node backend is unreachable (e.g. inside the standalone Android APK).
const _fetchActionSingle = async (action: string, input: any, onProgress?: (partial: any) => void) => {
  // Native app (Capacitor): there is no backend at all — and Capacitor's local
  // server can answer unknown routes with a 200 HTML page, which would prevent
  // an error-based fallback. So go straight to the client-side engine.
  if (isNativeApp()) {
    try {
      const result = await callGeminiClientDirect(action, input);
      if (onProgress) onProgress(result);
      if (!result || Object.keys(result).length === 0) {
        return { content: "Error: No content generated.", imagePrompt: "Classroom scene" };
      }
      return result;
    } catch (clientErr: any) {
      checkAndReportApiError(clientErr, "Gemini");
      throw clientErr;
    }
  }

  try {
    return await _fetchActionSingleBackend(action, input, onProgress);
  } catch (error: any) {
    if (!isBackendUnavailable(error)) {
      throw error;
    }
    console.warn(`[AI Routing] Backend unavailable for '${action}' — using client-side Gemini engine.`);
    try {
      const result = await callGeminiClientDirect(action, input);
      if (onProgress) onProgress(result);
      if (!result || Object.keys(result).length === 0) {
        return { content: "Error: No content generated.", imagePrompt: "Classroom scene" };
      }
      return result;
    } catch (clientErr: any) {
      checkAndReportApiError(clientErr, "Gemini");
      throw clientErr;
    }
  }
};

const executeWithContinuation = async (action: string, input: any, onProgress?: (partial: any) => void) => {
  let attempts = 0;
  let accumulatedContent = "";
  let lastResult: any = null;

  while (attempts < 3) {
    const currentInput = attempts === 0 ? input : { ...input, existingContent: accumulatedContent };
    
    const result = await _fetchActionSingle(action, currentInput, (partial) => {
      if (onProgress && partial) {
        const combined = {
          ...partial,
          content: accumulatedContent ? (accumulatedContent + "\n" + (partial.content || "")) : (partial.content || "")
        };
        onProgress(combined);
      }
    });

    const newContent = result.content || "";
    if (attempts === 0) {
      accumulatedContent = newContent;
    } else {
      accumulatedContent += "\n" + newContent;
    }

    lastResult = { ...result, content: accumulatedContent };
    if (onProgress) {
      onProgress(lastResult);
    }

    if (!isContentTruncated(newContent) || newContent.length < 500) {
      break;
    }
    attempts++;
  }

  return lastResult;
};

