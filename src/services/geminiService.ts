export const runTextGrade = async (studentAnswers: string, memo: string, rubric: string, language: string = 'English') => {
  if (isNativeApp()) {
    return await callGeminiClientDirect("text-grade", { studentAnswers, memo, rubric, language });
  }
  try {
    const response = await axios.post("/api/gemini/action", {
      action: "text-grade",
      input: { studentAnswers, memo, rubric, language }
    });
    return response.data;
  } catch (error: any) {
    if (isBackendUnavailable(error)) {
      return await callGeminiClientDirect("text-grade", { studentAnswers, memo, rubric, language });
    }
    console.error("Express /api/gemini/action failed text-grade:", error.message || error);
    checkAndReportApiError(error, "Gemini");
    throw error;
  }
};

export const chatWithTutor = async (messages: any[]) => {
  if (isNativeApp()) {
    const result = await callGeminiClientDirect("chat", { messages });
    return result.text || "";
  }
  try {
    const response = await axios.post("/api/gemini/action", {
      action: "chat",
      input: { messages }
    });
    return response.data.text;
  } catch (error: any) {
    if (isBackendUnavailable(error)) {
      const result = await callGeminiClientDirect("chat", { messages });
      return result.text || "";
    }
    console.error("Express /api/gemini/action failed:", error.message || error);
    checkAndReportApiError(error, "Gemini");
    throw error;
  }
};
